#!/usr/bin/env bash
#
# project-scanner.sh
# Scans a project directory and produces a CLAUDE.md tailored to what it finds.
#
# Usage:
#   project-scanner.sh [project-dir]
#   defaults to current directory if no arg given
#
# Output:
#   writes CLAUDE.md.generated to the project root
#   prints the path to stdout

set -euo pipefail

TARGET="${1:-$(pwd)}"
TARGET="$(cd "$TARGET" && pwd)"
OUT="$TARGET/CLAUDE.md.generated"

GREEN='\033[0;32m'
YELLOW='\033[0;33m'
NC='\033[0m'

log()  { echo -e "${GREEN}[scan]${NC} $*" >&2; }
warn() { echo -e "${YELLOW}[scan]${NC} $*" >&2; }

cd "$TARGET"

# Detect project type
PROJECT_KIND="unknown"
LANGUAGE_TAGS=()
COMMANDS=()
LAYOUT_HINTS=()
TEST_FRAMEWORK="none detected"

if [[ -f "package.json" ]]; then
  PROJECT_KIND="node"
  LANGUAGE_TAGS+=("Node.js")

  PKG_MGR="npm"
  if [[ -f "pnpm-lock.yaml" ]]; then PKG_MGR="pnpm"; fi
  if [[ -f "yarn.lock" ]];        then PKG_MGR="yarn"; fi
  if [[ -f "bun.lockb" ]];        then PKG_MGR="bun"; fi

  COMMANDS+=("$PKG_MGR install")
  for s in dev build start test lint typecheck; do
    if grep -q "\"$s\"" package.json; then
      COMMANDS+=("$PKG_MGR run $s")
    fi
  done

  if grep -q '"next"' package.json;            then LANGUAGE_TAGS+=("Next.js"); fi
  if grep -q '"react"' package.json;           then LANGUAGE_TAGS+=("React"); fi
  if grep -q '"vue"' package.json;             then LANGUAGE_TAGS+=("Vue"); fi
  if grep -q '"svelte"' package.json;          then LANGUAGE_TAGS+=("Svelte"); fi
  if grep -q '"typescript"' package.json;      then LANGUAGE_TAGS+=("TypeScript"); fi
  if grep -q '"tailwindcss"' package.json;     then LANGUAGE_TAGS+=("Tailwind"); fi
  if grep -q '"vitest"' package.json;          then TEST_FRAMEWORK="vitest"; fi
  if grep -q '"jest"' package.json;            then TEST_FRAMEWORK="jest"; fi
  if grep -q '"playwright"' package.json;      then TEST_FRAMEWORK="playwright"; fi
fi

if [[ -f "pyproject.toml" || -f "setup.py" || -f "requirements.txt" ]]; then
  PROJECT_KIND="python"
  LANGUAGE_TAGS+=("Python")

  if [[ -f "uv.lock" ]];      then COMMANDS+=("uv sync" "uv run pytest"); fi
  if [[ -f "poetry.lock" ]];  then COMMANDS+=("poetry install" "poetry run pytest"); fi
  if [[ -f "Pipfile.lock" ]]; then COMMANDS+=("pipenv install" "pipenv run pytest"); fi

  if grep -q "fastapi" pyproject.toml 2>/dev/null;  then LANGUAGE_TAGS+=("FastAPI"); fi
  if grep -q "django" pyproject.toml 2>/dev/null;   then LANGUAGE_TAGS+=("Django"); fi
  if grep -q "flask" pyproject.toml 2>/dev/null;    then LANGUAGE_TAGS+=("Flask"); fi
  if grep -q "pytest" pyproject.toml 2>/dev/null;   then TEST_FRAMEWORK="pytest"; fi
fi

if [[ -f "go.mod" ]]; then
  PROJECT_KIND="go"
  LANGUAGE_TAGS+=("Go")
  COMMANDS+=("go mod tidy" "go build ./..." "go test ./..." "go vet ./...")
  TEST_FRAMEWORK="go test"
fi

if [[ -f "Cargo.toml" ]]; then
  PROJECT_KIND="rust"
  LANGUAGE_TAGS+=("Rust")
  COMMANDS+=("cargo build" "cargo test" "cargo clippy" "cargo fmt")
  TEST_FRAMEWORK="cargo test"
fi

# Detect layout
for d in src app pages components lib server packages apps tests; do
  if [[ -d "$d" ]]; then
    LAYOUT_HINTS+=("$d/")
  fi
done

# Detect monorepo
IS_MONOREPO="no"
if [[ -d "packages" || -d "apps" ]]; then IS_MONOREPO="yes"; fi
if [[ -f "pnpm-workspace.yaml" ]]; then IS_MONOREPO="yes"; fi
if grep -q '"workspaces"' package.json 2>/dev/null; then IS_MONOREPO="yes"; fi

# Detect git
HAS_GIT="no"
if [[ -d ".git" ]]; then HAS_GIT="yes"; fi

# Detect deploy target
DEPLOY_HINT=""
if [[ -f "vercel.json" || -d ".vercel" ]];   then DEPLOY_HINT="Vercel"; fi
if [[ -f "netlify.toml" ]];                  then DEPLOY_HINT="Netlify"; fi
if [[ -f "fly.toml" ]];                      then DEPLOY_HINT="Fly.io"; fi
if [[ -f "Dockerfile" ]];                    then DEPLOY_HINT="${DEPLOY_HINT:+$DEPLOY_HINT, }Docker"; fi
if [[ -d ".github/workflows" ]];             then DEPLOY_HINT="${DEPLOY_HINT:+$DEPLOY_HINT, }GitHub Actions"; fi

LAYOUT_RENDERED=""
for h in "${LAYOUT_HINTS[@]:-}"; do
  LAYOUT_RENDERED="$LAYOUT_RENDERED- $h"$'\n'
done
[[ -z "$LAYOUT_RENDERED" ]] && LAYOUT_RENDERED="- (no standard folders detected)\n"

COMMANDS_RENDERED=""
for c in "${COMMANDS[@]:-}"; do
  COMMANDS_RENDERED="$COMMANDS_RENDERED- \`$c\`"$'\n'
done
[[ -z "$COMMANDS_RENDERED" ]] && COMMANDS_RENDERED="- (no standard commands detected)\n"

TAGS_RENDERED=$(IFS=", "; echo "${LANGUAGE_TAGS[*]}")
[[ -z "$TAGS_RENDERED" ]] && TAGS_RENDERED="(none detected)"

cat > "$OUT" <<EOF
# CLAUDE.md

Auto-generated by project-scanner on $(date -u +"%Y-%m-%d"). Edit by hand to make it yours. Re-run the scanner only when the stack changes substantially.

## Project

Type detected: \`$PROJECT_KIND\`
Stack tags: $TAGS_RENDERED
Monorepo: $IS_MONOREPO
Deploy hints: ${DEPLOY_HINT:-none detected}
Test framework: $TEST_FRAMEWORK

## Layout

$LAYOUT_RENDERED

## Commands

$COMMANDS_RENDERED

## Conventions to fill in

The scanner cannot read your team's conventions. Add the following sections by hand:

- House style for naming (folders, files, components)
- Definition of done for a change
- Things never to do without asking
- Things to default to
- Voice for commits and PR descriptions

## Notes

Re-run the scanner with:

\`\`\`bash
$(realpath "$0") "$TARGET"
\`\`\`

The output goes to \`CLAUDE.md.generated\`. Diff against the existing \`CLAUDE.md\` and merge by hand.
EOF

log "wrote $OUT"
echo "$OUT"
